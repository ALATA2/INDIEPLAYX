const SUPPORTED_LANGS = ['it', 'en', 'fr', 'es', 'ja', 'zh', 'pt'];

export function getLanguage() {
  const stored = localStorage.getItem('indieplay_lang');
  if (stored && SUPPORTED_LANGS.includes(stored)) {
    return stored;
  }
  
  const browserLang = navigator.language.split('-')[0];
  if (SUPPORTED_LANGS.includes(browserLang)) {
    return browserLang;
  }
  
  return 'en';
}

export function setLanguage(lang) {
  if (SUPPORTED_LANGS.includes(lang)) {
    localStorage.setItem('indieplay_lang', lang);
    translatePage();
  }
}

export function translatePage() {
  const currentLang = getLanguage();
  const dict = translations[currentLang] || translations['en'];
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  const selectors = document.querySelectorAll('.lang-select-dropdown');
  selectors.forEach(sel => {
    if (sel.value !== currentLang) {
      sel.value = currentLang;
    }
  });
}

export function initLanguageSelectors() {
  const currentLang = getLanguage();
  
  document.querySelectorAll('.lang-select-dropdown').forEach(sel => {
    sel.value = currentLang;
    sel.onchange = (e) => {
      setLanguage(e.target.value);
    };
  });
  
  translatePage();
}
