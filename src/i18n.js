export const SUPPORTED_LANGS = ['it', 'en', 'fr', 'es', 'de', 'ja', 'zh', 'pt'];

// Cache for automatic neural translations of dynamic texts (descriptions, news, reviews, articles)
let translationCache = {};
try {
  const savedCache = localStorage.getItem('indieplay_tr_cache_v1');
  if (savedCache) translationCache = JSON.parse(savedCache);
} catch (e) {
  translationCache = {};
}

function saveTranslationCache() {
  try {
    localStorage.setItem('indieplay_tr_cache_v1', JSON.stringify(translationCache));
  } catch (e) {
    // ignore storage quota errors
  }
}

/**
 * Automatically detects the user's preferred language from localStorage or browser settings
 */
export function getLanguage() {
  const stored = localStorage.getItem('indieplay_lang');
  if (stored && SUPPORTED_LANGS.includes(stored)) {
    return stored;
  }

  // Check navigator.languages array first, then navigator.language
  const candidates = Array.isArray(navigator.languages) && navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language || navigator.userLanguage || 'it'];

  for (const raw of candidates) {
    if (!raw) continue;
    const short = raw.toLowerCase().split('-')[0];
    if (SUPPORTED_LANGS.includes(short)) {
      localStorage.setItem('indieplay_lang', short);
      return short;
    }
  }

  return 'it';
}

export function setLanguage(lang) {
  if (SUPPORTED_LANGS.includes(lang)) {
    localStorage.setItem('indieplay_lang', lang);
    document.documentElement.lang = lang;
    translatePage();
    window.dispatchEvent(new CustomEvent('indieplay:langchange', { detail: { lang } }));
  }
}

/**
 * Translates an arbitrary string dynamically to the target language using cached cloud translation
 */
export async function translateDynamicText(text, targetLang = getLanguage()) {
  if (!text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  if (!trimmed || trimmed.length < 2) return text;
  if (targetLang === 'it') return text;

  const cacheKey = `${targetLang}::${trimmed}`;
  if (translationCache[cacheKey]) {
    return translationCache[cacheKey];
  }

  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${encodeURIComponent(targetLang)}&dt=t&q=${encodeURIComponent(trimmed)}`;
    const res = await fetch(url);
    if (!res.ok) return text;
    const data = await res.json();
    if (Array.isArray(data) && Array.isArray(data[0])) {
      const translated = data[0].map(part => part[0]).join('');
      if (translated) {
        translationCache[cacheKey] = translated;
        saveTranslationCache();
        return translated;
      }
    }
  } catch (e) {
    // Fallback to original text if offline
  }
  return text;
}

/**
 * Automatically scans and translates dynamic/free-text elements on the page
 * when the selected language is changed
 */
export async function autoTranslateDOM(targetLang = getLanguage()) {
  const selectors = [
    '[data-auto-translate]',
    '#hero-main-desc',
    '.youtube-card-info h3',
    '.youtube-card-info p',
    '.news-card h3',
    '.news-card p',
    '.mag-article-card h3',
    '.mag-article-card p',
    '.detail-description',
    '.comment-body',
    '#about-modal p',
    '#privacy-modal p, #privacy-modal h4, #privacy-modal li',
    '#cookie-modal p, #cookie-modal h4, #cookie-modal li',
    '.account-main h1, .account-main h2, .account-main h3, .account-main h4, .account-main p, .account-main label'
  ].join(', ');

  const elements = document.querySelectorAll(selectors);
  for (const el of elements) {
    if (el.hasAttribute('data-i18n')) continue;
    // Skip elements that contain child inputs or complex interactive children
    if (el.querySelector('input, select, textarea, button')) continue;

    if (!el.dataset.origText) {
      el.dataset.origText = el.textContent.trim();
    }
    const orig = el.dataset.origText;
    if (!orig) continue;

    if (targetLang === 'it') {
      if (el.textContent !== orig) el.textContent = orig;
    } else {
      translateDynamicText(orig, targetLang).then(tr => {
        if (getLanguage() === targetLang && tr) {
          el.textContent = tr;
        }
      });
    }
  }
}

export function translatePage() {
  const currentLang = getLanguage();
  document.documentElement.lang = currentLang;
  const dict = translations[currentLang] || translations['en'];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  const selectors = document.querySelectorAll('.lang-select-dropdown');
  selectors.forEach(sel => {
    // Ensure DE option is present in all dropdowns
    if (!sel.querySelector('option[value="de"]')) {
      const opt = document.createElement('option');
      opt.value = 'de';
      opt.style.background = '#1a242f';
      opt.style.color = 'white';
      opt.textContent = 'DE';
      sel.appendChild(opt);
    }
    if (sel.value !== currentLang) {
      sel.value = currentLang;
    }
  });

  // Automatically translate remaining dynamic content on the page
  autoTranslateDOM(currentLang);
}

export function initLanguageSelectors() {
  const currentLang = getLanguage();

  document.querySelectorAll('.lang-select-dropdown').forEach(sel => {
    if (!sel.querySelector('option[value="de"]')) {
      const opt = document.createElement('option');
      opt.value = 'de';
      opt.style.background = '#1a242f';
      opt.style.color = 'white';
      opt.textContent = 'DE';
      sel.appendChild(opt);
    }
    sel.value = currentLang;
    sel.onchange = (e) => {
      setLanguage(e.target.value);
    };
  });

  translatePage();
}
